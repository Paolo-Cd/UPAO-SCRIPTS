--. Mostrar  la decision  de 'DECISION_DE_RRHH', 
--. Mostrar los requerimientos ordenados por FECHA_DE_SOLICUTD de mayor a menor.
 ALTER PROCEDURE dbo.BuscarSolicitantePorDNI
 @ListaDNIS VARCHAR (MAX) 
AS 
BEGIN
	SET NOCOUNT ON ;

	select S.DNI,S.NOMBRES_Y_APELLIDOS,S.NUMERO_DE_TELEFONO ,R.DECISION_DE_RRHH ,R.FECHA_DE_SOLICITUD, R.NUMERO_DE_PLAZAS from SOLICITANTE S
	JOIN ASIGNACION A ON S.DNI = A.DNI
	JOIN REQUERIMIENTOS R ON A.ID_REQUERIMIENTO = R.ID_REQUERIMIENTO
	 WHERE S.DNI  IN (SELECT LTRIM(value) FROM string_split(@ListaDNIS,',') )
	ORDER BY R.FECHA_DE_SOLICITUD DESC;
	END
GO
