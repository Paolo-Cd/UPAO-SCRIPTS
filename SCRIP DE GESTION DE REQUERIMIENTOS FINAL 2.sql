--Construye una consulta que muestre AREA, PUESTO, cantidad de requerimientos y total de plazas.
--Debe usar al menos dos INNER JOIN, GROUP BY, HAVING y ORDER BY. Después conviértela en un
--PROCEDURE que reciba como parámetro el ID del área
USE GESTION_DE_REQUERIMIENTOS
GO
ALTER PROCEDURE DBO.ConsultarPlazasPorID_ARE
@ID_are int
as
begin
set nocount on ;

SELECT S.NOMBRES_Y_APELLIDOS AS 'SOLICITANTE',R.FECHA_DE_SOLICITUD, AR .NOMBRE AS 'AREA' , P.NOMBRE_DEL_PUESTO AS'PUESTO' 
,COUNT(R.ID_REQUERIMIENTO) AS 'CANTIDAD DE REQUERIMIENTOS',
SUM(R.NUMERO_DE_PLAZAS) AS 'TOTAL DE PLAZAS'

FROM ARE_DE_REQUERIMIENTO AR
JOIN REQUERIMIENTOS R ON AR.ID_ARE_DE_REQUERIMIENTO = R.ID_ARE_DE_REQUERIMIENTO
JOIN PUESTOS_DISPONIBLES P ON R.ID_PUESTO = P.ID_PUESTO
JOIN ASIGNACION A ON A.ID_REQUERIMIENTO =R.ID_REQUERIMIENTO
JOIN SOLICITANTE S ON S.DNI = A.DNI
WHERE AR.ID_ARE_DE_REQUERIMIENTO = @ID_are
GROUP BY 
S.NOMBRES_Y_APELLIDOS,R.FECHA_DE_SOLICITUD,
AR.NOMBRE , P.NOMBRE_DEL_PUESTO

HAVING
SUM(ISNULL(R.NUMERO_DE_PLAZAS,0)) >= 0

ORDER BY 'TOTAL DE PLAZAS' DESC;
end
GO

exec DBO.ConsultarPlazasPorID_ARE  2013;


